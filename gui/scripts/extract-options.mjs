// Extracts the scrcpy CLI option table from app/src/cli.c into
// src/options.json, so the GUI always matches the flags of this source tree.
//
//   node scripts/extract-options.mjs
//
// Rules mirror `struct sc_option` in cli.c:
//   no argdesc                    -> "none"     (boolean flag)
//   argdesc && optional_arg       -> "optional" (must be passed as --opt=value)
//   argdesc && !optional_arg      -> "required"
// Entries without .text are hidden from `scrcpy --help` and are skipped.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cliPath = resolve(here, '../../app/src/cli.c');
const outPath = resolve(here, '../src/options.json');

const src = readFileSync(cliPath, 'utf8');

const start = src.indexOf('static const struct sc_option options[] = {');
if (start < 0) throw new Error('options[] table not found in cli.c');
const end = src.indexOf('\n};', start);
let table = src.slice(start, end);

// Resolve the preprocessor blocks inside the table: keep the release (#else)
// branch of `#ifndef NDEBUG`, keep the body of any other conditional.
{
  const out = [];
  const stack = []; // each: { keep: bool }
  for (const line of table.split('\n')) {
    const t = line.trim();
    if (/^#\s*ifndef\s+NDEBUG/.test(t)) { stack.push({ keep: false, ndebug: true }); continue; }
    if (/^#\s*if/.test(t)) { stack.push({ keep: true }); continue; }
    if (/^#\s*else/.test(t)) { const top = stack.at(-1); top.keep = top.ndebug ? true : false; continue; }
    if (/^#\s*endif/.test(t)) { stack.pop(); continue; }
    if (stack.every((s) => s.keep)) out.push(line);
  }
  table = out.join('\n');
}

function unescapeC(s) {
  return s.replace(/\\(.)/g, (_, c) => ({ n: '\n', t: '\t', '"': '"', '\\': '\\', "'": "'" }[c] ?? c));
}

// Read a sequence of adjacent C string literals starting at `i`.
function readStrings(body, i) {
  let out = '';
  const re = /\s*"((?:[^"\\]|\\.)*)"/y;
  re.lastIndex = i;
  let m;
  while ((m = re.exec(body))) out += unescapeC(m[1]);
  return out;
}

// Split the table into top-level { ... } entries.
const entries = [];
{
  const bodyStart = table.indexOf('{') + 1;
  let depth = 0, inStr = false, from = -1;
  for (let i = bodyStart; i < table.length; i++) {
    const c = table[i];
    if (inStr) { if (c === '\\') i++; else if (c === '"') inStr = false; continue; }
    if (c === '"') { inStr = true; continue; }
    if (c === '{') { if (depth === 0) from = i; depth++; }
    else if (c === '}') { depth--; if (depth === 0) entries.push(table.slice(from + 1, i)); }
  }
}

const options = [];
let withText = 0;
for (const body of entries) {
  const field = (name) => {
    const m = new RegExp(`\\.${name}\\s*=`).exec(body);
    return m ? m.index + m[0].length : -1;
  };
  const textAt = field('text');
  if (textAt < 0) continue;
  const text = readStrings(body, textAt);
  if (!text) continue;
  withText++;

  const longAt = field('longopt');
  const name = longAt >= 0 ? readStrings(body, longAt) : null;
  const shortMatch = /\.shortopt\s*=\s*'(.)'/.exec(body);
  const argAt = field('argdesc');
  const argdesc = argAt >= 0 ? readStrings(body, argAt) : null;
  const optional = /\.optional_arg\s*=\s*true/.test(body);

  options.push({
    name,
    short: shortMatch ? shortMatch[1] : null,
    arg: !argdesc ? 'none' : optional ? 'optional' : 'required',
    argdesc,
    text,
  });
}

if (options.length !== withText) throw new Error('count mismatch');
const nameless = options.filter((o) => !o.name && !o.short);
if (nameless.length) throw new Error('options without long name: ' + JSON.stringify(nameless));

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(options, null, 2) + '\n');
// Same data as a plain script for the sandboxed renderer (no fetch of file://).
writeFileSync(
  outPath.replace(/\.json$/, '.js'),
  '// Generated by scripts/extract-options.mjs from app/src/cli.c. Do not edit.\n' +
    'globalThis.ScrcpyOptions = ' + JSON.stringify(options, null, 2) + ';\n',
);
console.log(`Extracted ${options.length} options (of ${entries.length} table entries) -> ${outPath}`);
